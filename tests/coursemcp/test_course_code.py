def test_a_hung_sync_never_holds_a_tool_call(client, monkeypatch) -> None:
    """The regression test for "nothing a student waits on touches GitHub"."""
    app = client.application
    search(client, "s_axilite")                         # a copy is in hand
    sync = library(app).sync_for("alpha")
    release, calls = threading.Event(), []
    blocking_git(monkeypatch, release, calls)
    state = sync.state()
    state["synced_at"] = state["last_attempt"] = time.time() - 10_000   # stale
    sync._write_state(state)
    try:
        for name, args in [("search_demos", {"query": "always_ff"}),
                           ("list_demos", {}),
                           ("get_demo_file", {"path": "demos/fsm/counter.sv"}),
                           ("list_demo_files", {"demo": "fsm"})]:
            result = within(2, lambda: call_tool(client, name, {"course_id": "alpha", **args}))
            assert not result.get("isError"), result
        # A refresh did start, off the request path, and is stuck on the network.
        deadline = time.monotonic() + 10
        while "ls-remote" not in calls and time.monotonic() < deadline:
            time.sleep(0.05)
        assert "ls-remote" in calls and sync._thread.is_alive()
    finally:
        release.set()
        if sync._thread:
            sync._thread.join(30)


def test_a_new_commit_is_served_after_the_ttl(app, client, tmp_path) -> None:
    search(client, "s_axilite")
    sync = library(app).sync_for("alpha")
    old = sync.snapshot.commit
    repo = tmp_path / "hwdesign"
    (repo / "demos/fsm/counter.sv").write_text("module counter;\n  // NEW_MARKER\nendmodule\n",
                                               encoding="utf-8")
    new = commit_all(repo)
    assert search(client, "NEW_MARKER")["hits"] == []   # within the TTL: the old copy
    state = sync.state()
    state["synced_at"] = state["last_attempt"] = time.time() - 10_000
    sync._write_state(state)
    search(client, "NEW_MARKER")                        # answered from the old copy...
    sync._thread.join(30)
    assert sync.snapshot.commit == new != old           # ...and the next sees the new one
    assert search(client, "NEW_MARKER")["hits_shown"] == 1


def test_a_failed_sync_keeps_serving_and_a_restart_loads_from_disk(app, client, tmp_path,
                                                                   monkeypatch) -> None:
    search(client, "s_axilite")
    sync = library(app).sync_for("alpha")
    good = sync.snapshot.commit
    monkeypatch.setattr(code_module, "remote_url", lambda config: (tmp_path / "gone").as_uri())
    assert sync.sync_now() is False
    assert sync.snapshot.commit == good
    assert sync.state()["last_error"]
    assert search(client, "s_axilite")["hits_shown"] >= 1
    # A restarted process: no network, the copy on disk.
    fresh = code_module.CodeSync("alpha", sync.config, sync.dir, ttl=10_000)
    calls = []
    real = code_module.run_git
    monkeypatch.setattr(code_module, "run_git", lambda args, **kw: calls.append(args[0]) or real(args, **kw))
    assert fresh.ensure().commit == good
    assert calls == ["rev-parse"]


def test_a_commit_with_a_broken_overrides_file_is_not_served(app, client, tmp_path) -> None:
    search(client, "s_axilite")
    sync = library(app).sync_for("alpha")
    good = sync.snapshot.commit
    repo = tmp_path / "hwdesign"
    (repo / "demos/demos.xml").write_text("<demos><demo id='fsm'><bogus/></demo></demos>",
                                          encoding="utf-8")
    commit_all(repo)
    assert sync.sync_now() is False
    assert sync.snapshot.commit == good
    assert "demos.xml" in sync.state()["last_error"]


def test_a_corrupt_mirror_is_cloned_again(app, client) -> None:
    search(client, "s_axilite")
    sync = library(app).sync_for("alpha")
    good = sync.snapshot.commit
    (sync.mirror / ".git" / "HEAD").unlink()
    assert sync.sync_now() is True
    assert sync.snapshot.commit == good
    assert (sync.mirror / ".git" / "HEAD").is_file()
    assert not (sync.dir / "mirror.new").exists() and not (sync.dir / "mirror.old").exists()


def test_concurrent_refreshes_run_one_sync(app, client, monkeypatch) -> None:
    search(client, "s_axilite")
    sync = library(app).sync_for("alpha")
    release, calls = threading.Event(), []
    blocking_git(monkeypatch, release, calls)
    started = [sync.refresh_in_background() for _ in range(5)]
    release.set()
    sync._thread.join(30)
    assert started.count(True) == 1
    assert calls.count("ls-remote") == 1


def test_a_forked_process_gets_its_own_syncs(app, client, monkeypatch) -> None:
    search(client, "s_axilite")
    lib = library(app)
    first = lib.sync_for("alpha")
    real_pid = os.getpid()
    monkeypatch.setattr(os, "getpid", lambda: real_pid + 1)
    assert lib.sync_for("alpha") is not first
