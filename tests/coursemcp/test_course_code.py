def git(*args, cwd) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True,
                          text=True).stdout


def commit_all(repo: Path, message: str = "update") -> str:
    git("add", "-A", cwd=repo)
    git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", message, cwd=repo)
    return git("rev-parse", "HEAD", cwd=repo).strip()


def make_repo(root: Path) -> Path:
    repo = root / "hwdesign"
    for path, text in REPO_FILES.items():
        (repo / path).parent.mkdir(parents=True, exist_ok=True)
        (repo / path).write_text(text, encoding="utf-8")
    for path, data in REPO_BINARIES.items():
        (repo / path).parent.mkdir(parents=True, exist_ok=True)
        (repo / path).write_bytes(data)
    git("init", "-q", "-b", "main", cwd=repo)
    git("config", "uploadpack.allowFilter", "true", cwd=repo)
    commit_all(repo, "demos")
    return repo


def write_materials(package: Path, code: dict | None = CODE_CONFIG) -> None:
    """A course package's MCP material: two decks and, optionally, <code>."""
    root = package / "mcp_materials"
    manifest = {"version": 1, "decks": [], "units": [], "unit_types": []}
    for deck_id, (unit, slides) in DECKS.items():
        count = max(slides)
        deck_dir = root / "slides" / deck_id
        deck_dir.mkdir(parents=True)
        entries = []
        for n in range(1, count + 1):
            spec = slides.get(n, {})
            entries.append({"n": n, "title": f"{deck_id} {n}", "text": spec.get("text", ""),
                            "notes": "", "image": None, "description": "",
                            "links": spec.get("links", [])})
        (deck_dir / "deck.json").write_text(json.dumps(
            {"id": deck_id, "unit": unit, "title": deck_id, "slides": entries}), encoding="utf-8")
        manifest["decks"].append({"id": deck_id, "unit": unit, "title": deck_id,
                                  "slides": count, "images": False, "warning": ""})
    if code is not None:
        manifest["code"] = code
    (root / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")


def make_app(tmp_path, monkeypatch, *, code_switch: bool = True, repo: Path | None = None):
    if code_switch:
        monkeypatch.setenv("LLMGRADER_MCP_CODE", "1")
    else:
        monkeypatch.delenv("LLMGRADER_MCP_CODE", raising=False)
    monkeypatch.delenv("LLMGRADER_CODE_SYNC_TTL_S", raising=False)
    repo = repo or make_repo(tmp_path)
    monkeypatch.setattr(code_module, "remote_url", lambda config: repo.as_uri())
    app = build_app(tmp_path, monkeypatch, enabled=True)
    storage = tmp_path / "storage" / "courses"
    write_materials(storage / "alpha" / "soln_pkg")
    write_materials(storage / "beta" / "soln_pkg", code=None)
    return app


