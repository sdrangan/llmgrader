def blocking_git(monkeypatch, release: threading.Event, calls: list):
    """run_git that hangs on any network command until *release* is set."""
    real = code_module.run_git

    def run(args, **kwargs):
        calls.append(args[0])
        if args[0] in ("clone", "ls-remote", "fetch"):
            release.wait(30)
        return real(args, **kwargs)

    monkeypatch.setattr(code_module, "run_git", run)


