def is_build_output(path: str) -> bool:
    parts = path.split("/")[:-1]
    return any(part in BUILD_DIRS or any(fnmatch.fnmatchcase(part, g) for g in BUILD_DIR_GLOBS)
               for part in parts)


def _excluded_by_config(path: str, excludes: tuple[str, ...]) -> bool:
    name = posixpath.basename(path)
    for pattern in excludes:
        target = path if "/" in pattern else name
        if fnmatch.fnmatchcase(target, pattern):
            return True
    return False


def language_of(path: str, text: str = "") -> str | None:
    name = posixpath.basename(path)
    language = CODE_FILENAMES.get(name) or CODE_EXTENSIONS.get(posixpath.splitext(name)[1].lower())
    if language == "cpp" and "#pragma HLS" in text:
        return "hls-cpp"
    return language


def flatten_notebook(raw: str) -> str | None:
    """A notebook as text: each cell's source under a marker line, outputs dropped."""
    try:
        notebook = json.loads(raw)
    except ValueError:
        return None
    lines = []
    for number, cell in enumerate(notebook.get("cells", []), start=1):
        source = cell.get("source", "")
        if isinstance(source, list):
            source = "".join(source)
        lines.append(f"# ---- cell {number} [{cell.get('cell_type', 'code')}] ----")
        lines.extend(source.splitlines())
        lines.append("")
    return "\n".join(lines)


_FRONT_MATTER_KEY = re.compile(r"^([A-Za-z_][\w-]*)\s*:\s*(.*?)\s*$")


def split_front_matter(lines: list[str]) -> tuple[dict, int]:
    """``(front matter, index of the first body line)`` of a Markdown page.

    Only flat ``key: value`` lines are read -- title, parent, nav_order are
    all that is used -- so no YAML library is needed.
    """
    if not lines or lines[0].strip() != "---":
        return {}, 0
    for end in range(1, len(lines)):
        if lines[end].strip() == "---":
            meta = {}
            for line in lines[1:end]:
                match = _FRONT_MATTER_KEY.match(line)
                if match:
                    meta[match.group(1)] = match.group(2).strip().strip("'\"")
            return meta, end + 1
    return {}, 0


_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_MD_LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def heading_anchor(text: str) -> str:
    """The id kramdown gives a heading: GitHub Pages' default for just-the-docs."""
    text = _MD_LINK.sub(r"\1", text)
    text = re.sub(r"[^\w\- ]|_", "", text).lower().replace(" ", "-")
    return re.sub(r"^[^a-z]+", "", text)


def _headings(lines: tuple[str, ...]) -> tuple:
    """For each line, the nearest Markdown heading at or above it: ``(text, anchor)``."""
    current = None
    in_fence = False
    result = []
    for line in lines:
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
        elif not in_fence:
            match = _HEADING.match(line)
            if match:
                text = _MD_LINK.sub(r"\1", match.group(2)).replace("`", "").strip()
                current = (text, heading_anchor(match.group(2)))
        result.append(current)
    return tuple(result)


def _normalize(line: str) -> str:
    return " ".join(line.split()).lower()


@dataclass
class SourceFile:
    """One servable file.  *lines* are the served lines; the first of them is
    line *first_line* of the file on GitHub (docs drop their front matter)."""

    path: str
    kind: str                 # "code" or "doc"
    language: str
    lines: tuple[str, ...]
    first_line: int = 1
    meta: dict = field(default_factory=dict)
    norm: tuple[str, ...] = ()
    headings: tuple | None = None

    @property
    def last_line(self) -> int:
        return self.first_line + len(self.lines) - 1

    @property
    def title(self) -> str:
        if self.meta.get("title"):
            return self.meta["title"]
        for line in self.lines:
            match = _HEADING.match(line)
            if match:
                return _MD_LINK.sub(r"\1", match.group(2)).replace("`", "").strip()
        return posixpath.basename(self.path)

    def first_paragraph(self, limit: int = 400) -> str:
        """The first prose paragraph: what a docs page or README says it is."""
        paragraph: list[str] = []
        in_fence = False
        for line in self.lines:
            stripped = line.strip()
            if stripped.startswith(("```", "~~~")):
                in_fence = not in_fence
                if paragraph:
                    break
                continue
            if in_fence:
                continue
            if not stripped or stripped.startswith(("#", "|", "---", "{:", "<", "!")):
                if paragraph:
                    break
                continue
            paragraph.append(stripped)
        text = " ".join(paragraph)
        return text[:limit] + ("…" if len(text) > limit else "")


def _make_source(path: str, kind: str, text: str) -> SourceFile | None:
    language = language_of(path, text)
    if language is None:
        return None
    raw_lines = text.splitlines()
    meta, start = ({}, 0)
    if language == "markdown":
        meta, start = split_front_matter(raw_lines)
    lines = tuple(raw_lines[start:])
    return SourceFile(
        path=path, kind=kind, language=language, lines=lines, first_line=start + 1,
        meta=meta, norm=tuple(_normalize(line) for line in lines),
        headings=_headings(lines) if language == "markdown" else None,
    )


def read_servable(full: Path, path: str, kind: str, excludes: tuple[str, ...]) -> SourceFile | None:
    """*full* as a :class:`SourceFile`, or None if it is not to be served."""
    if is_build_output(path) or _excluded_by_config(path, excludes):
        return None
    if kind == "doc" and not path.lower().endswith(".md"):
        return None
    if language_of(path) is None:
        return None
    try:
        if full.is_symlink() or not full.is_file():
            return None
        data = full.read_bytes()
    except OSError:
        return None
    if b"\0" in data[:8192]:
        return None
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return None
    if path.endswith(".ipynb"):
        text = flatten_notebook(text)
        if text is None:
            return None
    if len(text.encode("utf-8")) > MAX_FILE_BYTES:
        return None
    if path.endswith(".tcl"):
        head = "\n".join(text.splitlines()[:10])
        if any(marker in head for marker in GENERATED_TCL_MARKERS):
            return None
    return _make_source(path, kind, text)


