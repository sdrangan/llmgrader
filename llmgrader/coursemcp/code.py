def run_git(args: list[str], *, cwd: str | Path | None = None,
            timeout: float = GIT_TIMEOUT_S) -> str:
    """Run one git command; its stdout, or a GitError.

    Never prompts: a repo that has gone private must fail now, not wait for
    a password nobody will type, and no credential helper may open a window.
    """
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0", GCM_INTERACTIVE="never")
    try:
        result = subprocess.run(
            ["git", "-c", "credential.helper=", "-c", "core.askPass=", *args],
            cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout,
        )
    except subprocess.TimeoutExpired as exc:
        raise GitError(f"git {args[0]} timed out after {timeout:.0f}s") from exc
    except OSError as exc:
        raise GitError(f"git could not run: {exc}") from exc
    if result.returncode != 0:
        raise GitError(f"git {args[0]} failed: {(result.stderr or result.stdout).strip()[:300]}")
    return result.stdout


def _rmtree(path: Path) -> None:
    """``shutil.rmtree`` that also removes git's read-only pack files on Windows."""
    def make_writable(func, target, _exc):
        try:
            os.chmod(target, stat.S_IWRITE)
            func(target)
        except OSError:
            pass
    if path.exists():
        shutil.rmtree(path, onerror=make_writable)


class _FileLock:
    """An flock on *path*, across gunicorn workers.  A no-op on Windows, where
    the dev server is a single process."""

    def __init__(self, path: Path, *, exclusive: bool):
        self.path, self.exclusive = path, exclusive
        self.handle = None
        self.acquired = False

    def __enter__(self) -> bool:
        try:
            import fcntl
        except ImportError:
            self.acquired = True
            return True
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.handle = open(self.path, "a+")
        mode = (fcntl.LOCK_EX if self.exclusive else fcntl.LOCK_SH) | fcntl.LOCK_NB
        try:
            fcntl.flock(self.handle, mode)
            self.acquired = True
        except OSError:
            self.acquired = False
        return self.acquired

    def __exit__(self, *exc) -> None:
        if self.handle is not None:
            if self.acquired:
                import fcntl
                fcntl.flock(self.handle, fcntl.LOCK_UN)
            self.handle.close()


class SnapshotRejected(Exception):
    """A new commit that must not replace the copy being served."""


def validate_snapshot(snapshot: CodeSnapshot) -> None:
    """Refuse a commit that would empty the tools or has a broken overrides file."""
    if not snapshot.files:
        raise SnapshotRejected("no servable files under the <include> paths")
    from llmgrader.coursemcp.demo_links import OverridesError, parse_overrides

    try:
        parse_overrides(snapshot.overrides_text)
    except OverridesError as exc:
        raise SnapshotRejected(f"{snapshot.config.links_path}: {exc}") from exc


class CodeSync:
    """One course's copy of its demo repo: the mirror, the snapshot, the syncing."""

    def __init__(self, course_id: str, config: CodeConfig, directory: str | Path,
                 *, ttl: float | None = None):
        self.course_id = course_id
        self.config = config
        self.dir = Path(directory)
        self.mirror = self.dir / "mirror"
        self.state_path = self.dir / "state.json"
        self.ttl = ttl if ttl is not None else _ttl_from_env()
        self._snapshot: CodeSnapshot | None = None
        self._sync_lock = threading.Lock()
        self._load_lock = threading.Lock()
        self._thread: threading.Thread | None = None
        self._index_key = None
        self._index = None
        self._index_refs = None     # keeps the keyed objects alive, so ids are not reused

    @property
    def snapshot(self) -> CodeSnapshot | None:
        return self._snapshot

    # -- state.json ----------------------------------------------------------

    def state(self) -> dict:
        try:
            return json.loads(self.state_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}

    def _write_state(self, state: dict) -> None:
        self.dir.mkdir(parents=True, exist_ok=True)
        tmp = self.state_path.with_suffix(".tmp")
        tmp.write_text(json.dumps(state, indent=1), encoding="utf-8")
        tmp.replace(self.state_path)

    def _stale(self, state: dict) -> bool:
        last = max(state.get("synced_at") or 0, state.get("last_attempt") or 0)
        return time.time() - last >= self.ttl

    # -- serving -------------------------------------------------------------

    def ensure(self, *, wait: float = 0.0) -> CodeSnapshot | None:
        """The snapshot to serve, starting a background refresh if it is stale.

        Waits (up to *wait* seconds) only when there is no copy at all.
        """
        if self._snapshot is None:
            self._load_from_disk()
        state = self.state()
        if (self._snapshot is not None and state.get("commit")
                and state["commit"] != self._snapshot.commit):
            self._load_from_disk()    # another worker synced
        if self._snapshot is None or self._stale(state):
            self.refresh_in_background()
        if self._snapshot is None and wait > 0:
            thread = self._thread
            if thread is not None:
                thread.join(wait)
        return self._snapshot

    def last_error(self) -> str | None:
        return self.state().get("last_error")

    def index(self, snapshot: CodeSnapshot, materials):
        """The demo link graph for *snapshot* and the course's slides, cached."""
        from llmgrader.coursemcp.demo_links import build_index, slides_from_materials

        key = (id(snapshot), id(materials))
        if self._index_key != key or self._index is None:
            index = build_index(snapshot, slides_from_materials(materials))
            self._index, self._index_key = index, key
            self._index_refs = (snapshot, materials)
        return self._index

    def _load_from_disk(self) -> None:
        with self._load_lock:
            if not (self.mirror / ".git").is_dir():
                return
            with _FileLock(self.dir / ".lock", exclusive=False) as got:
                if not got:
                    return      # a sync is mid-way in another worker; try later
                try:
                    commit = run_git(["rev-parse", "HEAD"], cwd=self.mirror, timeout=15).strip()
                    if self._snapshot is not None and self._snapshot.commit == commit:
                        return
                    snapshot = build_snapshot(self.mirror, self.config, commit)
                    validate_snapshot(snapshot)
                except (GitError, SnapshotRejected, OSError) as exc:
                    print(f"[CourseCode] {self.course_id}: copy on disk not loaded: {exc}")
                    return
                self._snapshot = snapshot

    # -- syncing -------------------------------------------------------------

    def refresh_in_background(self) -> bool:
        """Start a sync on a thread unless one is running; True if started."""
        if not self._sync_lock.acquire(blocking=False):
            return False

        def run():
            try:
                self._sync()
            except Exception as exc:  # a thread must never die loudly mid-request
                print(f"[CourseCode] {self.course_id}: sync crashed: {exc!r}")
            finally:
                self._sync_lock.release()

        try:
            thread = threading.Thread(target=run, daemon=True,
                                      name=f"course-code-sync-{self.course_id}")
            self._thread = thread
            thread.start()
        except Exception:
            self._sync_lock.release()
            raise
        return True

    def sync_now(self) -> bool:
        """Sync in this thread (tests, tools).  True if the copy is current."""
        with self._sync_lock:
            return self._sync()

    def _sync(self) -> bool:
        with _FileLock(self.dir / ".lock", exclusive=True) as got:
            if not got:
                return False
            state = self.state()
            state["last_attempt"] = time.time()
            ok = False
            try:
                commit = self._fetch(state)
                if self._snapshot is None or self._snapshot.commit != commit:
                    snapshot = build_snapshot(self.mirror, self.config, commit)
                    validate_snapshot(snapshot)
                    self._snapshot = snapshot
                    print(f"[CourseCode] {self.course_id}: serving {commit[:12]} "
                          f"({len(snapshot.files)} files)")
                state.update(commit=commit, synced_at=time.time(), last_error=None)
                ok = True
            except (GitError, SnapshotRejected, OSError) as exc:
                state["last_error"] = str(exc)[:500]
                print(f"[CourseCode] {self.course_id}: sync failed, serving the last good "
                      f"copy: {exc}")
            finally:
                try:
                    self._write_state(state)
                except OSError as exc:
                    print(f"[CourseCode] {self.course_id}: could not write state: {exc}")
            return ok

    def _mirror_head(self) -> str | None:
        if not (self.mirror / ".git").is_dir():
            return None
        try:
            return run_git(["rev-parse", "HEAD"], cwd=self.mirror, timeout=15).strip()
        except GitError:
            return None

    def _fetch(self, state: dict) -> str:
        """Bring the mirror up to the branch head; return the commit it is at."""
        remote = remote_url(self.config)
        patterns = self.config.sparse_patterns()
        head = self._mirror_head()
        if head is None or state.get("remote") != remote:
            self._clone(remote, patterns)
        else:
            listing = run_git(["ls-remote", remote, f"refs/heads/{self.config.branch}"])
            remote_head = listing.split()[0] if listing.strip() else None
            if remote_head is None:
                raise GitError(f"branch {self.config.branch!r} not found in {self.config.repo}")
            if remote_head != head or state.get("patterns") != patterns:
                try:
                    if state.get("patterns") != patterns:
                        run_git(["sparse-checkout", "set", "--no-cone", *patterns], cwd=self.mirror)
                    run_git(["fetch", "--depth", "1", "--filter=blob:none", "origin",
                             self.config.branch], cwd=self.mirror)
                    run_git(["reset", "-q", "--hard", "FETCH_HEAD"], cwd=self.mirror)
                except GitError as exc:
                    print(f"[CourseCode] {self.course_id}: mirror update failed ({exc}); "
                          "cloning afresh")
                    self._clone(remote, patterns)
        state.update(remote=remote, patterns=patterns)
        head = self._mirror_head()
        if head is None:
            raise GitError("the mirror has no commit after syncing")
        return head

    def _clone(self, remote: str, patterns: list[str]) -> None:
        """Clone into ``mirror.new`` and move it into place only once complete."""
        self.dir.mkdir(parents=True, exist_ok=True)
        new, old = self.dir / "mirror.new", self.dir / "mirror.old"
        _rmtree(new)
        run_git(["clone", "-q", "--depth", "1", "--filter=blob:none", "--no-checkout",
                 "--branch", self.config.branch, remote, str(new)])
        run_git(["sparse-checkout", "set", "--no-cone", *patterns], cwd=new)
        run_git(["reset", "-q", "--hard", "HEAD"], cwd=new)
        _rmtree(old)
        if self.mirror.exists():
            self.mirror.rename(old)
        new.rename(self.mirror)
        _rmtree(old)


def _ttl_from_env() -> float:
    try:
        return float(os.environ.get("LLMGRADER_CODE_SYNC_TTL_S", "") or DEFAULT_TTL_S)
    except ValueError:
        return DEFAULT_TTL_S


class CodeLibrary:
    """One :class:`CodeSync` per course that publishes demos, per process.

    Rebuilt after a fork, like ``CourseMCPRunner``: a lock copied from the
    parent mid-sync would stay held forever in the child.
    """

    def __init__(self, registry, *, ttl: float | None = None):
        self.registry = registry
        self.ttl = ttl
        self._lock = threading.Lock()
        self._pid = os.getpid()
        self._syncs: dict[str, CodeSync] = {}

    def config_for(self, course_id: str) -> CodeConfig | None:
        from llmgrader.coursemcp.materials import load_materials

        materials = load_materials(self.registry.grader_for(course_id).soln_pkg)
        if materials is None or not materials.code:
            return None
        return CodeConfig.from_dict(materials.code)

    def sync_for(self, course_id: str) -> CodeSync | None:
        config = self.config_for(course_id)
        if config is None:
            return None
        with self._lock:
            if self._pid != os.getpid():
                self._syncs, self._pid = {}, os.getpid()
            existing = self._syncs.get(course_id)
            if existing is not None and existing.config == config:
                return existing
            sync = CodeSync(course_id, config,
                            Path(self.registry.course_dir(course_id)) / "code", ttl=self.ttl)
            self._syncs[course_id] = sync
            return sync

    def warm(self) -> None:
        """Load or refresh every course's copy, without waiting on any of it."""
        for entry in self.registry.courses():
            try:
                sync = self.sync_for(entry.id)
                if sync is not None:
                    sync.ensure(wait=0)
            except Exception as exc:
                print(f"[CourseCode] {entry.id}: {exc!r}")

    def code_version(self, course_id) -> str | None:
        """The commit being served for *course_id*, if any.  Never syncs."""
        if not isinstance(course_id, str):
            return None
        sync = self._syncs.get(course_id)
        snapshot = sync.snapshot if sync is not None else None
        return snapshot.short_commit if snapshot is not None else None
